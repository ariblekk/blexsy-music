                val artistRuns = flexCols.getOrNull(1)?.jsonObject?.get("musicResponsiveListItemFlexColumnRenderer")?.jsonObject?.get("text")?.jsonObject?.get("runs")?.jsonArray
                val trackArtist = artistRuns?.firstOrNull()?.jsonObject?.get("text")?.jsonPrimitive?.content ?: artist

                atvVideoIds.add(videoId)
                Track(
                    id = videoId,
                    title = cleanTrackTitle(trackTitle),
                    artist = trackArtist,
                    album = title,
                    image = image,
                    youtubeId = videoId
                )
            }

            AlbumDetail(
                id = targetBrowseId,
                name = title,
                artist = artist,
                image = image,
                year = year,
                type = if (tracks.size <= 2) "SINGLE" else "ALBUM",
                tracks = tracks
            )
        } catch (_: Exception) {
            null
        }
    }

    /**
     * Direct LRC lyrics fetch from LRCLIB (open source, synced lyrics).
     */
    suspend fun getLyrics(title: String, artist: String, durationMs: Long? = null): LyricsResult? = withContext(Dispatchers.IO) {
        val cleanTitle = cleanTrackTitle(title)
        val cleanArtist = cleanArtist(artist)
        val durSec = if (durationMs != null && durationMs > 0) durationMs / 1000 else null

        val url = "https://lrclib.net/api/get?track_name=${cleanTitle.encodeURLQueryComponent()}&artist_name=${cleanArtist.encodeURLQueryComponent()}" +
                (if (durSec != null) "&duration=$durSec" else "")

        try {
            val res: HttpResponse = client.get(url) {
                header("User-Agent", "Blexsy/1.0 (+https://blexsy.my.id)")
            }
            if (!res.status.isSuccess()) return@withContext null
            val obj = json.parseToJsonElement(res.bodyAsText()).jsonObject
            val synced = obj["syncedLyrics"]?.jsonPrimitive?.content
            val plain = obj["plainLyrics"]?.jsonPrimitive?.content
            val lrc = synced ?: plain
            if (!lrc.isNullOrBlank()) {
                LyricsResult(lyrics = lrc, source = "LRCLIB")
            } else null
        } catch (_: Exception) {
            null
        }
    }

    private fun extractMusicVideoType(item: JsonObject): String? {
        val overlayType = item["overlay"]?.jsonObject
            ?.get("musicItemThumbnailOverlayRenderer")?.jsonObject
            ?.get("content")?.jsonObject
            ?.get("musicPlayButtonRenderer")?.jsonObject
            ?.get("playNavigationEndpoint")?.jsonObject
            ?.get("watchEndpoint")?.jsonObject
            ?.get("watchEndpointMusicSupportedConfigs")?.jsonObject
            ?.get("watchEndpointMusicConfig")?.jsonObject
            ?.get("musicVideoType")?.jsonPrimitive?.content
        if (!overlayType.isNullOrBlank()) return overlayType

        val navType = item["navigationEndpoint"]?.jsonObject
            ?.get("watchEndpoint")?.jsonObject
            ?.get("watchEndpointMusicSupportedConfigs")?.jsonObject
            ?.get("watchEndpointMusicConfig")?.jsonObject
            ?.get("musicVideoType")?.jsonPrimitive?.content
        if (!navType.isNullOrBlank()) return navType

        val flexRuns = item["flexColumns"]?.jsonArray?.firstOrNull()?.jsonObject
            ?.get("musicResponsiveListItemFlexColumnRenderer")?.jsonObject
            ?.get("text")?.jsonObject?.get("runs")?.jsonArray
        return flexRuns?.firstOrNull()?.jsonObject
            ?.get("navigationEndpoint")?.jsonObject
            ?.get("watchEndpoint")?.jsonObject
            ?.get("watchEndpointMusicSupportedConfigs")?.jsonObject
            ?.get("watchEndpointMusicConfig")?.jsonObject
            ?.get("musicVideoType")?.jsonPrimitive?.content
    }

    fun cleanTrackTitle(raw: String): String {
        return raw
            .replace(Regex("""\s*\[[^]]*]"""), "")
            .replace(Regex("""(?i)\s*\((?:official\s*)?(?:music\s*)?(?:live\s*)?(?:video|mv|audio|visualizer|live|remaster(?:ed)?|version|edit|mix|remix|dc musik)[^)]*\)"""), "")
            .replace(Regex("""(?i)\s*-\s*(?:official\s*)?(?:music\s*)?(?:live\s*)?(?:video|mv|audio|visualizer|live|remaster(?:ed)?|version|edit|mix|remix)\b.*$"""), "")
            .replace(Regex("""(?i)\b(?:official\s*)?(?:music\s*)?(?:live\s*)?(?:video|mv|dc musik)\b"""), "")
            .trim('-', ' ')
            .replace(Regex("""\s+"""), " ")
            .trim()
    }

    fun cleanArtist(raw: String): String {
        return raw
            .split(Regex("""(?i)\s*(?:,|&|feat\.?|ft\.?|featuring|with|×|x)\s*"""))
            .firstOrNull()
            ?.trim()
            ?.ifBlank { raw } ?: raw
    }

    private fun parseDurationMs(durationText: String): Long {
        val parts = durationText.trim().split(":")
        if (parts.size == 2) {
            val mins = parts[0].toLongOrNull() ?: 0L
            val secs = parts[1].toLongOrNull() ?: 0L
            return (mins * 60 + secs) * 1000
        }
        return 0L
    }
