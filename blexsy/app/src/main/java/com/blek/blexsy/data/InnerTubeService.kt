    suspend fun getVisitorData(context: Context? = null): String = withContext(Dispatchers.IO) {
        cachedVisitorData?.let { return@withContext it }

        if (context != null) {
            val saved = context.getSharedPreferences("blexsy_prefs", Context.MODE_PRIVATE)
                .getString("yt_visitor_data", null)
            if (!saved.isNullOrBlank()) {
                cachedVisitorData = saved
                return@withContext saved
            }
        }

        try {
            val response: HttpResponse = client.get(SW_JS_URL)
            val text = response.bodyAsText()
            val match = Regex(VISITOR_REGEX).find(text)
            val visitor = match?.value ?: "CgtWV3I3ekdTX2RGZyiAh5DXBjIKCgJJRBIEGgAgG2KqAgqnAkN0b0JD"
            cachedVisitorData = visitor
            if (context != null) {
                context.getSharedPreferences("blexsy_prefs", Context.MODE_PRIVATE)
                    .edit().putString("yt_visitor_data", visitor).apply()
            }
            visitor
        } catch (_: Exception) {
            "CgtWV3I3ekdTX2RGZyiAh5DXBjIKCgJJRBIEGgAgG2KqAgqnAkN0b0JD"
        }
    }

    /**
     * Resolves direct, un-ciphered GoogleVideo audio stream URL using VISIONOS client.
     * Guaranteed no 403 chunk errors when fetched with Referer: https://www.youtube.com/
     */
    suspend fun resolveStreamUrl(
        context: Context? = null,
        videoId: String,
        audioQuality: String = "high"
    ): String? = withContext(Dispatchers.IO) {
        val visitor = getVisitorData(context)
        val bodyJson = buildJsonObject {
            putJsonObject("context") {
                putJsonObject("client") {
                    put("clientName", "VISIONOS")
                    put("clientVersion", "0.1")
                    put("osName", "visionOS")
                    put("osVersion", "1.3.21O771")
                    put("deviceMake", "Apple")
                    put("deviceModel", "RealityDevice14,1")
                    put("gl", "US")
                    put("hl", "en")
                    put("visitorData", visitor)
                }
            }
            put("videoId", videoId)
        }

        try {
            val res: HttpResponse = client.post(PLAYER_API_URL) {
                contentType(ContentType.Application.Json)
                header("User-Agent", USER_AGENT_VISIONOS)
                setBody(bodyJson)
            }
            val text = res.bodyAsText()
            val root = json.parseToJsonElement(text).jsonObject
            val status = root["playabilityStatus"]?.jsonObject?.get("status")?.jsonPrimitive?.content
            if (status != "OK") return@withContext null

            val formats = root["streamingData"]?.jsonObject?.get("adaptiveFormats")?.jsonArray ?: return@withContext null
            val audioFormats = formats.mapNotNull { it.jsonObject }.filter {
                val mime = it["mimeType"]?.jsonPrimitive?.content.orEmpty()
                val url = it["url"]?.jsonPrimitive?.content.orEmpty()
                mime.startsWith("audio/") && url.isNotBlank()
            }
            if (audioFormats.isEmpty()) return@withContext null

            val chosen = when (audioQuality.lowercase()) {
                "low" -> audioFormats.firstOrNull { it["itag"]?.jsonPrimitive?.intOrNull in listOf(249, 139) }
                    ?: audioFormats.minByOrNull { it["bitrate"]?.jsonPrimitive?.intOrNull ?: 0 }
                "normal" -> audioFormats.firstOrNull { it["itag"]?.jsonPrimitive?.intOrNull in listOf(140, 250) }
                    ?: audioFormats.sortedBy { it["bitrate"]?.jsonPrimitive?.intOrNull ?: 0 }.getOrNull(audioFormats.size / 2)
                else -> audioFormats.firstOrNull { it["itag"]?.jsonPrimitive?.intOrNull == 251 }
                    ?: audioFormats.firstOrNull { it["itag"]?.jsonPrimitive?.intOrNull == 140 }
                    ?: audioFormats.maxByOrNull { it["bitrate"]?.jsonPrimitive?.intOrNull ?: 0 }
            } ?: audioFormats.first()

            chosen["url"]?.jsonPrimitive?.content
        } catch (_: Exception) {
            null
        }
    }

    /**
     * Resolves a Track to a direct audio stream URL.
     * If the track is a video version (OMV/UGC) or has no verified ATV audio id,
     * queries YouTube Music once to swap for the official studio ATV version.
     */
    suspend fun resolveTrackStream(
        context: Context? = null,
        track: Track,
        audioQuality: String = "high"
    ): String? = withContext(Dispatchers.IO) {
        val directYtId = track.youtubeId?.takeIf { it.isNotBlank() && it.length == 11 && atvVideoIds.contains(it) }
        val idToUse = if (directYtId != null) {
            directYtId
        } else {
            val cacheKey = "${track.displayTitle}|${track.artist}".lowercase()
            videoIdCache[cacheKey] ?: run {
                val query = "${cleanTrackTitle(track.displayTitle)} ${cleanArtist(track.artist)}"
                val results = searchTracks(query, limit = 3)
                val topMatch = results.firstOrNull()?.youtubeId ?: results.firstOrNull()?.id
                if (topMatch != null) {
                    videoIdCache[cacheKey] = topMatch
                    atvVideoIds.add(topMatch)
                    topMatch
                } else {
                    track.youtubeId?.takeIf { it.isNotBlank() && it.length == 11 }
                        ?: track.id.takeIf { it.length == 11 && !it.contains("-") }
                }
            }
        }

        if (idToUse != null) {
            resolveStreamUrl(context, idToUse, audioQuality)
        } else {
            null
        }
    }

    /**
     * Search songs directly via YouTube Music InnerTube API (WEB_REMIX).
     * Filters out non-audio YouTube videos (OMV, live clips, UGC, fan uploads)
     * so only pure studio tracks (MUSIC_VIDEO_TYPE_ATV) are returned.
     */
    suspend fun searchTracks(query: String, limit: Int = 20): List<Track> = withContext(Dispatchers.IO) {
        if (query.isBlank()) return@withContext emptyList()
        val bodyJson = buildJsonObject {
            putJsonObject("context") {
                putJsonObject("client") {
                    put("clientName", "WEB_REMIX")
                    put("clientVersion", "1.20260707.12.00")
                    put("gl", "ID")
                    put("hl", "id")
                }
            }
            put("query", query)
            put("params", "EgWKAQIIAWoKEAkQBRAKEAMQBA%3D%3D") // Filter songs
        }

        try {
            val res: HttpResponse = client.post(SEARCH_API_URL) {
                contentType(ContentType.Application.Json)
                header("User-Agent", USER_AGENT_WEB)
                header("Referer", "https://music.youtube.com/")
                header("X-YouTube-Client-Name", "67")
                header("X-YouTube-Client-Version", "1.20260707.12.00")
                setBody(bodyJson)
            }
            val root = json.parseToJsonElement(res.bodyAsText()).jsonObject
            val tabs = root["contents"]?.jsonObject?.get("tabbedSearchResultsRenderer")
                ?.jsonObject?.get("tabs")?.jsonArray ?: return@withContext emptyList()
            val sectionList = tabs.firstOrNull()?.jsonObject?.get("tabRenderer")
                ?.jsonObject?.get("content")?.jsonObject?.get("sectionListRenderer")
                ?.jsonObject?.get("contents")?.jsonArray ?: return@withContext emptyList()

            val songsShelf = sectionList.firstOrNull()?.jsonObject?.get("musicShelfRenderer")?.jsonObject
                ?: return@withContext emptyList()
            val items = songsShelf["contents"]?.jsonArray ?: return@withContext emptyList()

            val parsed = items.mapNotNull { itemElem ->
                val item = itemElem.jsonObject["musicResponsiveListItemRenderer"]?.jsonObject ?: return@mapNotNull null
                val videoId = item["playlistItemData"]?.jsonObject?.get("videoId")?.jsonPrimitive?.content ?: return@mapNotNull null
                val flexCols = item["flexColumns"]?.jsonArray ?: return@mapNotNull null
                if (flexCols.size < 2) return@mapNotNull null

                val titleRuns = flexCols[0].jsonObject["musicResponsiveListItemFlexColumnRenderer"]
                    ?.jsonObject?.get("text")?.jsonObject?.get("runs")?.jsonArray
                val rawTitle = titleRuns?.firstOrNull()?.jsonObject?.get("text")?.jsonPrimitive?.content ?: "Unknown Track"

                val artistRuns = flexCols[1].jsonObject["musicResponsiveListItemFlexColumnRenderer"]
                    ?.jsonObject?.get("text")?.jsonObject?.get("runs")?.jsonArray
                val artist = artistRuns?.firstOrNull()?.jsonObject?.get("text")?.jsonPrimitive?.content ?: "Unknown Artist"
                val album = artistRuns?.getOrNull(2)?.jsonObject?.get("text")?.jsonPrimitive?.content.orEmpty()
                val artistBrowseIds = artistRuns?.mapNotNull {
                    runCatching { it.jsonObject["navigationEndpoint"]?.jsonObject?.get("browseEndpoint")?.jsonObject?.get("browseId")?.jsonPrimitive?.content }.getOrNull()
                }?.filter { it.startsWith("UC") || it.startsWith("FEmusic_artist") }.orEmpty()
                val albumBrowseId = artistRuns?.mapNotNull {
                    runCatching { it.jsonObject["navigationEndpoint"]?.jsonObject?.get("browseEndpoint")?.jsonObject?.get("browseId")?.jsonPrimitive?.content }.getOrNull()
                }?.firstOrNull { it.startsWith("MPREb_") || it.startsWith("VL") }

                val durationText = artistRuns?.lastOrNull()?.jsonObject?.get("text")?.jsonPrimitive?.content.orEmpty()
                val durationMs = parseDurationMs(durationText)

                val thumbnails = item["thumbnail"]?.jsonObject?.get("musicThumbnailRenderer")
                    ?.jsonObject?.get("thumbnail")?.jsonObject?.get("thumbnails")?.jsonArray
                val rawImage = thumbnails?.lastOrNull()?.jsonObject?.get("url")?.jsonPrimitive?.content
                val image = rawImage?.replace(Regex("=w\\d+-h\\d+[^\"'\\s]*"), "=w1024-h1024")
                    ?.replace(Regex("=s\\d+[^\"'\\s]*"), "=w1024-h1024")

                val mvt = extractMusicVideoType(item)
                val isOfficial = isOfficialRelease(
                    musicVideoType = mvt,
                    imageUrl = rawImage,
                    rawTitle = rawTitle,
                    hasAlbum = album.isNotBlank() || albumBrowseId != null
                )

                if (!isOfficial) return@mapNotNull null

                atvVideoIds.add(videoId)

                Track(
                    id = videoId,
                    title = cleanTrackTitle(rawTitle),
                    artist = artist,
                    album = album,
                    image = image,
                    albumId = albumBrowseId,
                    artistIds = artistBrowseIds,
                    youtubeId = videoId,
                    durationMs = durationMs
                )
            }

            parsed.take(limit)
        } catch (_: Exception) {
            emptyList()
        }
    }

