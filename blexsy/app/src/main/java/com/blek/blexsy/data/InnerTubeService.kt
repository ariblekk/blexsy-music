    suspend fun getVisitorData(context: Context? = null): String = withContext(Dispatchers.IO) {
        cachedVisitorData?.let { return@withContext it }
        val ctx = context ?: appContext

        if (ctx != null) {
            val saved = ctx.getSharedPreferences("blexsy_prefs", Context.MODE_PRIVATE)
                .getString("yt_visitor_data", null)
            // Only trust a value fetched from the network; the hardcoded fallback goes stale and
            // makes the player API answer UNPLAYABLE, which silently kills the canvas.
            if (!saved.isNullOrBlank() && saved != FALLBACK_VISITOR_DATA) {
                cachedVisitorData = saved
                return@withContext saved
            }
        }

        fetchVisitorData()?.let { visitor ->
            cachedVisitorData = visitor
            ctx?.getSharedPreferences("blexsy_prefs", Context.MODE_PRIVATE)
                ?.edit()?.putString("yt_visitor_data", visitor)?.apply()
            return@withContext visitor
        }
        FALLBACK_VISITOR_DATA
    }

    /** Fetches a visitor id from the service-worker bootstrap, or null when unavailable. */
    private suspend fun fetchVisitorData(): String? = try {
        val response: HttpResponse = client.get(SW_JS_URL) {
            header("User-Agent", USER_AGENT_WEB)
        }
        val text = response.bodyAsText()
        Regex(VISITOR_REGEX).find(text)?.value
    } catch (_: Exception) {
        null
    }

    suspend fun resolveStreamUrl(
        context: Context? = null,
        videoId: String,
        audioQuality: String = "high"
    ): String? = withContext(Dispatchers.IO) {
        val visitor = getVisitorData(context)
        val bodyJson = buildJsonObject {
            putJsonObject("context") {
                putJsonObject("client") {
                    put("clientName", "VISIONOS")
                    put("clientVersion", "0.1")
                    put("osName", "visionOS")
                    put("osVersion", "1.3.21O771")
                    put("deviceMake", "Apple")
                    put("deviceModel", "RealityDevice14,1")
                    put("gl", "US")
                    put("hl", "en")
                    put("visitorData", visitor)
                }
            }
            put("videoId", videoId)
        }

        try {
            val res: HttpResponse = client.post(PLAYER_API_URL) {
                contentType(ContentType.Application.Json)
                header("User-Agent", USER_AGENT_VISIONOS)
                setBody(bodyJson)
            }
            val text = res.bodyAsText()
            val root = json.parseToJsonElement(text).jsonObject
            val status = root["playabilityStatus"]?.jsonObject?.get("status")?.jsonPrimitive?.content
            if (status != "OK") return@withContext null

            val formats = root["streamingData"]?.jsonObject?.get("adaptiveFormats")?.jsonArray ?: return@withContext null
            val audioFormats = formats.mapNotNull { it.jsonObject }.filter {
                val mime = it["mimeType"]?.jsonPrimitive?.content.orEmpty()
                val url = it["url"]?.jsonPrimitive?.content.orEmpty()
                mime.startsWith("audio/") && url.isNotBlank()
            }
            if (audioFormats.isEmpty()) return@withContext null

            val chosen = when (audioQuality.lowercase()) {
                "low" -> audioFormats.firstOrNull { it["itag"]?.jsonPrimitive?.intOrNull in listOf(249, 139) }
                    ?: audioFormats.minByOrNull { it["bitrate"]?.jsonPrimitive?.intOrNull ?: 0 }
                "normal" -> audioFormats.firstOrNull { it["itag"]?.jsonPrimitive?.intOrNull in listOf(140, 250) }
                    ?: audioFormats.sortedBy { it["bitrate"]?.jsonPrimitive?.intOrNull ?: 0 }.getOrNull(audioFormats.size / 2)
                else -> audioFormats.firstOrNull { it["itag"]?.jsonPrimitive?.intOrNull == 251 }
                    ?: audioFormats.firstOrNull { it["itag"]?.jsonPrimitive?.intOrNull == 140 }
                    ?: audioFormats.maxByOrNull { it["bitrate"]?.jsonPrimitive?.intOrNull ?: 0 }
            } ?: audioFormats.first()

            chosen["url"]?.jsonPrimitive?.content
        } catch (_: Exception) {
            null
        }
    }

    /**
     * Resolves a Track to a direct audio stream URL.
     * If the track is a video version (OMV/UGC) or has no verified ATV audio id,
     * queries YouTube Music once to swap for the official studio ATV version.
     */
    suspend fun resolveTrackStream(
        context: Context? = null,
        track: Track,
        audioQuality: String = "high"
    ): String? = withContext(Dispatchers.IO) {
        val directYtId = track.youtubeId?.takeIf { it.isNotBlank() && it.length == 11 && atvVideoIds.contains(it) }
        val idToUse = if (directYtId != null) {
            directYtId
        } else {
            val cacheKey = "${track.displayTitle}|${track.artist}".lowercase()
            videoIdCache[cacheKey] ?: run {
                val query = "${cleanTrackTitle(track.displayTitle)} ${cleanArtist(track.artist)}"
                val results = searchTracks(query, limit = 3)
                val topMatch = results.firstOrNull()?.youtubeId ?: results.firstOrNull()?.id
                if (topMatch != null) {
                    videoIdCache[cacheKey] = topMatch
                    atvVideoIds.add(topMatch)
                    topMatch
                } else {
                    track.youtubeId?.takeIf { it.isNotBlank() && it.length == 11 }
                        ?: track.id.takeIf { it.length == 11 && !it.contains("-") }
                }
            }
        }

        if (idToUse != null) {
            resolveStreamUrl(context, idToUse, audioQuality)
        } else {
            null
        }
    }

    /**
     * Search songs directly via YouTube Music InnerTube API (WEB_REMIX).
     * Filters out non-audio YouTube videos (OMV, live clips, UGC, fan uploads)
     * so only pure studio tracks (MUSIC_VIDEO_TYPE_ATV) are returned.
     */
    suspend fun searchTracks(query: String, limit: Int = 20): List<Track> = withContext(Dispatchers.IO) {
        if (query.isBlank()) return@withContext emptyList()
        val bodyJson = buildJsonObject {
            putJsonObject("context") {
                putJsonObject("client") {
                    put("clientName", "WEB_REMIX")
                    put("clientVersion", "1.20260707.12.00")
                    put("gl", "ID")
                    put("hl", "id")
                }
            }
            put("query", query)
            put("params", "EgWKAQIIAWoKEAkQBRAKEAMQBA%3D%3D") // Filter songs
        }

        try {
            val res: HttpResponse = client.post(SEARCH_API_URL) {
                contentType(ContentType.Application.Json)
                header("User-Agent", USER_AGENT_WEB)
                header("Referer", "https://music.youtube.com/")
                header("X-YouTube-Client-Name", "67")
                header("X-YouTube-Client-Version", "1.20260707.12.00")
                setBody(bodyJson)
            }
            val root = json.parseToJsonElement(res.bodyAsText()).jsonObject
            val tabs = root["contents"]?.jsonObject?.get("tabbedSearchResultsRenderer")
                ?.jsonObject?.get("tabs")?.jsonArray ?: return@withContext emptyList()
            val sectionList = tabs.firstOrNull()?.jsonObject?.get("tabRenderer")
                ?.jsonObject?.get("content")?.jsonObject?.get("sectionListRenderer")
                ?.jsonObject?.get("contents")?.jsonArray ?: return@withContext emptyList()

            val songsShelf = sectionList.firstOrNull()?.jsonObject?.get("musicShelfRenderer")?.jsonObject
                ?: return@withContext emptyList()
            val items = songsShelf["contents"]?.jsonArray ?: return@withContext emptyList()

            val parsed = items.mapNotNull { itemElem ->
                val item = itemElem.jsonObject["musicResponsiveListItemRenderer"]?.jsonObject ?: return@mapNotNull null
                val videoId = item["playlistItemData"]?.jsonObject?.get("videoId")?.jsonPrimitive?.content ?: return@mapNotNull null
                val flexCols = item["flexColumns"]?.jsonArray ?: return@mapNotNull null
                if (flexCols.size < 2) return@mapNotNull null

                val titleRuns = flexCols[0].jsonObject["musicResponsiveListItemFlexColumnRenderer"]
                    ?.jsonObject?.get("text")?.jsonObject?.get("runs")?.jsonArray
                val rawTitle = titleRuns?.firstOrNull()?.jsonObject?.get("text")?.jsonPrimitive?.content ?: "Unknown Track"

                val artistRuns = flexCols[1].jsonObject["musicResponsiveListItemFlexColumnRenderer"]
                    ?.jsonObject?.get("text")?.jsonObject?.get("runs")?.jsonArray
                val artist = artistRuns?.firstOrNull()?.jsonObject?.get("text")?.jsonPrimitive?.content ?: "Unknown Artist"
                val album = artistRuns?.getOrNull(2)?.jsonObject?.get("text")?.jsonPrimitive?.content.orEmpty()
                val artistBrowseIds = artistRuns?.mapNotNull {
                    runCatching { it.jsonObject["navigationEndpoint"]?.jsonObject?.get("browseEndpoint")?.jsonObject?.get("browseId")?.jsonPrimitive?.content }.getOrNull()
                }?.filter { it.startsWith("UC") || it.startsWith("FEmusic_artist") }.orEmpty()
                val albumBrowseId = artistRuns?.mapNotNull {
                    runCatching { it.jsonObject["navigationEndpoint"]?.jsonObject?.get("browseEndpoint")?.jsonObject?.get("browseId")?.jsonPrimitive?.content }.getOrNull()
                }?.firstOrNull { it.startsWith("MPREb_") || it.startsWith("VL") }

                val durationText = artistRuns?.lastOrNull()?.jsonObject?.get("text")?.jsonPrimitive?.content.orEmpty()
                val durationMs = parseDurationMs(durationText)

                val thumbnails = item["thumbnail"]?.jsonObject?.get("musicThumbnailRenderer")
                    ?.jsonObject?.get("thumbnail")?.jsonObject?.get("thumbnails")?.jsonArray
                val rawImage = thumbnails?.lastOrNull()?.jsonObject?.get("url")?.jsonPrimitive?.content
                val image = rawImage?.replace(Regex("=w\\d+-h\\d+[^\"'\\s]*"), "=w1024-h1024")
                    ?.replace(Regex("=s\\d+[^\"'\\s]*"), "=w1024-h1024")

                val mvt = extractMusicVideoType(item)
                val isOfficial = isOfficialRelease(
                    musicVideoType = mvt,
                    imageUrl = rawImage,
                    rawTitle = rawTitle,
                    hasAlbum = album.isNotBlank() || albumBrowseId != null
                )

                if (!isOfficial) return@mapNotNull null

                atvVideoIds.add(videoId)

                Track(
                    id = videoId,
                    title = cleanTrackTitle(rawTitle),
                    artist = artist,
                    album = album,
                    image = image,
                    albumId = albumBrowseId,
                    artistIds = artistBrowseIds,
                    youtubeId = videoId,
                    durationMs = durationMs
                )
            }

            parsed.take(limit)
        } catch (_: Exception) {
            emptyList()
        }
    }

    /**
     * Fetches automix radio tracks directly via YouTube Music InnerTube (/youtubei/v1/next).
     * Returns a pair of recommended tracks and the continuation token for infinite playback.
     */
    suspend fun getRadioTracks(videoId: String, continuation: String? = null): Pair<List<Track>, String?> = withContext(Dispatchers.IO) {
        try {
            val endpointBody = if (!continuation.isNullOrBlank()) {
                buildJsonObject {
                    putJsonObject("context") {
                        putJsonObject("client") {
                            put("clientName", "WEB_REMIX")
                            put("clientVersion", "1.20260707.12.00")
                            put("gl", "ID")
                            put("hl", "id")
                        }
                    }
                    put("continuation", continuation)
                }
            } else {
                val initialBody = buildJsonObject {
                    putJsonObject("context") {
                        putJsonObject("client") {
                            put("clientName", "WEB_REMIX")
                            put("clientVersion", "1.20260707.12.00")
                            put("gl", "ID")
                            put("hl", "id")
                        }
                    }
                    put("videoId", videoId)
                }
                val initRes: HttpResponse = client.post(NEXT_API_URL) {
                    contentType(ContentType.Application.Json)
                    header("User-Agent", USER_AGENT_WEB)
                    header("Referer", "https://music.youtube.com/")
                    header("X-YouTube-Client-Name", "67")
                    header("X-YouTube-Client-Version", "1.20260707.12.00")
                    setBody(initialBody)
                }
                val initRoot = json.parseToJsonElement(initRes.bodyAsText()).jsonObject
                val tabs = initRoot["contents"]?.jsonObject?.get("singleColumnMusicWatchNextResultsRenderer")?.jsonObject
                    ?.get("tabbedRenderer")?.jsonObject?.get("watchNextTabbedResultsRenderer")?.jsonObject
                    ?.get("tabs")?.jsonArray
                val queuePanel = tabs?.firstOrNull()?.jsonObject?.get("tabRenderer")?.jsonObject
                    ?.get("content")?.jsonObject?.get("musicQueueRenderer")?.jsonObject
                    ?.get("content")?.jsonObject?.get("playlistPanelRenderer")?.jsonObject
                val queueContents = queuePanel?.get("contents")?.jsonArray

                var automixPlaylistId: String? = null
                var automixParams: String? = null
                if (queueContents != null) {
                    for (itemElem in queueContents) {
                        val endpoint = itemElem.jsonObject["automixPreviewVideoRenderer"]?.jsonObject
                            ?.get("content")?.jsonObject?.get("automixPlaylistVideoRenderer")?.jsonObject
                            ?.get("navigationEndpoint")?.jsonObject?.get("watchPlaylistEndpoint")?.jsonObject
                        if (endpoint != null) {
                            automixPlaylistId = endpoint["playlistId"]?.jsonPrimitive?.content
                            automixParams = endpoint["params"]?.jsonPrimitive?.content
                            break
                        }
                    }
                }

                if (automixPlaylistId != null && automixParams != null) {
                    buildJsonObject {
                        putJsonObject("context") {
                            putJsonObject("client") {
                                put("clientName", "WEB_REMIX")
                                put("clientVersion", "1.20260707.12.00")
                                put("gl", "ID")
                                put("hl", "id")
                            }
                        }
                        put("playlistId", automixPlaylistId)
                        put("params", automixParams)
                    }
                } else {
                    return@withContext (emptyList<Track>() to null)
                }
            }

            val res: HttpResponse = client.post(NEXT_API_URL) {
                contentType(ContentType.Application.Json)
                header("User-Agent", USER_AGENT_WEB)
                header("Referer", "https://music.youtube.com/")
                header("X-YouTube-Client-Name", "67")
                header("X-YouTube-Client-Version", "1.20260707.12.00")
                setBody(endpointBody)
            }
            val root = json.parseToJsonElement(res.bodyAsText()).jsonObject

            val playlistPanel = root["continuationContents"]?.jsonObject?.get("playlistPanelContinuation")?.jsonObject
                ?: root["contents"]?.jsonObject?.get("singleColumnMusicWatchNextResultsRenderer")?.jsonObject
                    ?.get("tabbedRenderer")?.jsonObject?.get("watchNextTabbedResultsRenderer")?.jsonObject
                    ?.get("tabs")?.jsonArray?.firstOrNull()?.jsonObject?.get("tabRenderer")?.jsonObject
                    ?.get("content")?.jsonObject?.get("musicQueueRenderer")?.jsonObject
                    ?.get("content")?.jsonObject?.get("playlistPanelRenderer")?.jsonObject

            val items = playlistPanel?.get("contents")?.jsonArray ?: return@withContext (emptyList<Track>() to null)
            val nextContinuation = playlistPanel["continuations"]?.jsonArray?.firstOrNull()?.jsonObject?.let {
                it["nextRadioContinuationData"]?.jsonObject?.get("continuation")?.jsonPrimitive?.content
                    ?: it["nextContinuationData"]?.jsonObject?.get("continuation")?.jsonPrimitive?.content
            }

            val tracks = items.mapNotNull { itemElem ->
                val r = itemElem.jsonObject["playlistPanelVideoRenderer"]?.jsonObject ?: return@mapNotNull null
                val vId = r["videoId"]?.jsonPrimitive?.content ?: return@mapNotNull null
                val rawTitle = r["title"]?.jsonObject?.get("runs")?.jsonArray?.firstOrNull()?.jsonObject
                    ?.get("text")?.jsonPrimitive?.content ?: "Track"
                val bylineRuns = r["longBylineText"]?.jsonObject?.get("runs")?.jsonArray
                val artist = bylineRuns?.firstOrNull()?.jsonObject?.get("text")?.jsonPrimitive?.content ?: "Artist"
                val album = bylineRuns?.getOrNull(2)?.jsonObject?.get("text")?.jsonPrimitive?.content.orEmpty()
                val durationText = r["lengthText"]?.jsonObject?.get("runs")?.jsonArray?.firstOrNull()?.jsonObject
                    ?.get("text")?.jsonPrimitive?.content.orEmpty()
                val durationMs = parseDurationMs(durationText)

                val thumbs = r["thumbnail"]?.jsonObject?.get("thumbnails")?.jsonArray
                val rawImage = thumbs?.lastOrNull()?.jsonObject?.get("url")?.jsonPrimitive?.content
                val image = rawImage?.replace(Regex("=w\\d+-h\\d+[^\"'\\s]*"), "=w1024-h1024")
                    ?.replace(Regex("=s\\d+[^\"'\\s]*"), "=w1024-h1024")

                if (rawImage != null && (rawImage.contains("i.ytimg.com") || rawImage.contains("/vi/"))) {
                    return@mapNotNull null
                }
                if (VIDEO_NOISE_REGEX.containsMatchIn(rawTitle)) {
                    return@mapNotNull null
                }

                atvVideoIds.add(vId)
                Track(
                    id = vId,
                    title = cleanTrackTitle(rawTitle),
                    artist = artist,
                    album = album,
                    image = image,
                    youtubeId = vId,
                    durationMs = durationMs
                )
            }
            Pair(tracks, nextContinuation)
        } catch (_: Exception) {
            Pair(emptyList(), null)
        }
    }

    /**
     * Direct LRC lyrics fetch from LRCLIB (open source, synced lyrics).
     */
    suspend fun getLyrics(title: String, artist: String, durationMs: Long? = null): LyricsResult? = withContext(Dispatchers.IO) {
        val cleanTitle = cleanTrackTitle(title)
        val cleanArtist = cleanArtist(artist)
        val durSec = if (durationMs != null && durationMs > 0) durationMs / 1000 else null

        val url = "https://lrclib.net/api/get?track_name=${cleanTitle.encodeURLQueryComponent()}&artist_name=${cleanArtist.encodeURLQueryComponent()}" +
                (if (durSec != null) "&duration=$durSec" else "")

        try {
            val res: HttpResponse = client.get(url) {
                header("User-Agent", "Blexsy/1.0 (+https://blexsy.my.id)")
            }
            if (!res.status.isSuccess()) return@withContext null
            val obj = json.parseToJsonElement(res.bodyAsText()).jsonObject
            val synced = obj["syncedLyrics"]?.jsonPrimitive?.content
            val plain = obj["plainLyrics"]?.jsonPrimitive?.content
            val lrc = synced ?: plain
            if (!lrc.isNullOrBlank()) {
                LyricsResult(lyrics = lrc, source = "LRCLIB")
            } else null
        } catch (_: Exception) {
            null
        }
    }

    private fun extractMusicVideoType(item: JsonObject): String? {
        val overlayType = item["overlay"]?.jsonObject
            ?.get("musicItemThumbnailOverlayRenderer")?.jsonObject
            ?.get("content")?.jsonObject
            ?.get("musicPlayButtonRenderer")?.jsonObject
            ?.get("playNavigationEndpoint")?.jsonObject
            ?.get("watchEndpoint")?.jsonObject
            ?.get("watchEndpointMusicSupportedConfigs")?.jsonObject
            ?.get("watchEndpointMusicConfig")?.jsonObject
            ?.get("musicVideoType")?.jsonPrimitive?.content
        if (!overlayType.isNullOrBlank()) return overlayType

        val navType = item["navigationEndpoint"]?.jsonObject
            ?.get("watchEndpoint")?.jsonObject
            ?.get("watchEndpointMusicSupportedConfigs")?.jsonObject
            ?.get("watchEndpointMusicConfig")?.jsonObject
            ?.get("musicVideoType")?.jsonPrimitive?.content
        if (!navType.isNullOrBlank()) return navType

        val flexRuns = item["flexColumns"]?.jsonArray?.firstOrNull()?.jsonObject
            ?.get("musicResponsiveListItemFlexColumnRenderer")?.jsonObject
            ?.get("text")?.jsonObject?.get("runs")?.jsonArray
        return flexRuns?.firstOrNull()?.jsonObject
            ?.get("navigationEndpoint")?.jsonObject
            ?.get("watchEndpoint")?.jsonObject
            ?.get("watchEndpointMusicSupportedConfigs")?.jsonObject
            ?.get("watchEndpointMusicConfig")?.jsonObject
            ?.get("musicVideoType")?.jsonPrimitive?.content
    }

    fun cleanTrackTitle(raw: String): String {
        return raw
            .replace(Regex("""\s*\[[^]]*]"""), "")
            .replace(Regex("""(?i)\s*\((?:official\s*)?(?:music\s*)?(?:live\s*)?(?:video|mv|audio|visualizer|live|remaster(?:ed)?|version|edit|mix|remix|dc musik)[^)]*\)"""), "")
            .replace(Regex("""(?i)\s*-\s*(?:official\s*)?(?:music\s*)?(?:live\s*)?(?:video|mv|audio|visualizer|live|remaster(?:ed)?|version|edit|mix|remix)\b.*$"""), "")
            .replace(Regex("""(?i)\b(?:official\s*)?(?:music\s*)?(?:live\s*)?(?:video|mv|dc musik)\b"""), "")
            .trim('-', ' ')
            .replace(Regex("""\s+"""), " ")
            .trim()
    }

    fun cleanArtist(raw: String): String {
        return raw
            .split(Regex("""(?i)\s*(?:,|&|feat\.?|ft\.?|featuring|with|×|x)\s*"""))
            .firstOrNull()
            ?.trim()
            ?.ifBlank { raw } ?: raw
    }

    private fun parseDurationMs(durationText: String): Long {
        val parts = durationText.trim().replace('.', ':').split(":")
            .mapNotNull { it.trim().toLongOrNull() }
        return when (parts.size) {
            1 -> parts[0] * 1000
            2 -> (parts[0] * 60 + parts[1]) * 1000
            3 -> (parts[0] * 3600 + parts[1] * 60 + parts[2]) * 1000
            else -> 0L
        }
    }

