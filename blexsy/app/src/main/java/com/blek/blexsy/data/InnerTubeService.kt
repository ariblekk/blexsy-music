    /**
     * Determines whether an item is an official studio release (Auto-generated by YouTube / Art Track).
     * Excludes music videos (OMV), fan uploads (UGC), and non-square YouTube player thumbnails (i.ytimg.com).
     */
    fun isOfficialRelease(
        musicVideoType: String?,
        imageUrl: String?,
        rawTitle: String,
        hasAlbum: Boolean = false
    ): Boolean {
        if (musicVideoType == MUSIC_VIDEO_TYPE_OMV || musicVideoType == MUSIC_VIDEO_TYPE_UGC) {
            return false
        }
        if (imageUrl != null && (imageUrl.contains("i.ytimg.com") || imageUrl.contains("/vi/"))) {
            return false
        }
        if (VIDEO_NOISE_REGEX.containsMatchIn(rawTitle)) {
            return false
        }
        if (musicVideoType == MUSIC_VIDEO_TYPE_ATV) {
            return true
        }
        val isGoogleSquareArt = imageUrl != null && (imageUrl.contains("googleusercontent.com") || imageUrl.contains("ggpht.com"))
        return isGoogleSquareArt && hasAlbum
    }

