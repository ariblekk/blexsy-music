    /**
     * Fetches automix radio tracks directly via YouTube Music InnerTube (/youtubei/v1/next).
     * Returns a pair of recommended tracks and the continuation token for infinite playback.
     */
    suspend fun getRadioTracks(videoId: String, continuation: String? = null): Pair<List<Track>, String?> = withContext(Dispatchers.IO) {
        try {
            val endpointBody = if (!continuation.isNullOrBlank()) {
                buildJsonObject {
                    putJsonObject("context") {
                        putJsonObject("client") {
                            put("clientName", "WEB_REMIX")
                            put("clientVersion", "1.20260707.12.00")
                            put("gl", "ID")
                            put("hl", "id")
                        }
                    }
                    put("continuation", continuation)
                }
            } else {
                val initialBody = buildJsonObject {
                    putJsonObject("context") {
                        putJsonObject("client") {
                            put("clientName", "WEB_REMIX")
                            put("clientVersion", "1.20260707.12.00")
                            put("gl", "ID")
                            put("hl", "id")
                        }
                    }
                    put("videoId", videoId)
                }
                val initRes: HttpResponse = client.post(NEXT_API_URL) {
                    contentType(ContentType.Application.Json)
                    header("User-Agent", USER_AGENT_WEB)
                    header("Referer", "https://music.youtube.com/")
                    header("X-YouTube-Client-Name", "67")
                    header("X-YouTube-Client-Version", "1.20260707.12.00")
                    setBody(initialBody)
                }
                val initRoot = json.parseToJsonElement(initRes.bodyAsText()).jsonObject
                val tabs = initRoot["contents"]?.jsonObject?.get("singleColumnMusicWatchNextResultsRenderer")?.jsonObject
                    ?.get("tabbedRenderer")?.jsonObject?.get("watchNextTabbedResultsRenderer")?.jsonObject
                    ?.get("tabs")?.jsonArray
                val queuePanel = tabs?.firstOrNull()?.jsonObject?.get("tabRenderer")?.jsonObject
                    ?.get("content")?.jsonObject?.get("musicQueueRenderer")?.jsonObject
                    ?.get("content")?.jsonObject?.get("playlistPanelRenderer")?.jsonObject
                val queueContents = queuePanel?.get("contents")?.jsonArray

                var automixPlaylistId: String? = null
                var automixParams: String? = null
                if (queueContents != null) {
                    for (itemElem in queueContents) {
                        val endpoint = itemElem.jsonObject["automixPreviewVideoRenderer"]?.jsonObject
                            ?.get("content")?.jsonObject?.get("automixPlaylistVideoRenderer")?.jsonObject
                            ?.get("navigationEndpoint")?.jsonObject?.get("watchPlaylistEndpoint")?.jsonObject
                        if (endpoint != null) {
                            automixPlaylistId = endpoint["playlistId"]?.jsonPrimitive?.content
                            automixParams = endpoint["params"]?.jsonPrimitive?.content
                            break
                        }
                    }
                }

                if (automixPlaylistId != null && automixParams != null) {
                    buildJsonObject {
                        putJsonObject("context") {
                            putJsonObject("client") {
                                put("clientName", "WEB_REMIX")
                                put("clientVersion", "1.20260707.12.00")
                                put("gl", "ID")
                                put("hl", "id")
                            }
                        }
                        put("playlistId", automixPlaylistId)
                        put("params", automixParams)
                    }
                } else {
                    return@withContext (emptyList<Track>() to null)
                }
            }

            val res: HttpResponse = client.post(NEXT_API_URL) {
                contentType(ContentType.Application.Json)
                header("User-Agent", USER_AGENT_WEB)
                header("Referer", "https://music.youtube.com/")
                header("X-YouTube-Client-Name", "67")
                header("X-YouTube-Client-Version", "1.20260707.12.00")
                setBody(endpointBody)
            }
            val root = json.parseToJsonElement(res.bodyAsText()).jsonObject

            val playlistPanel = root["continuationContents"]?.jsonObject?.get("playlistPanelContinuation")?.jsonObject
                ?: root["contents"]?.jsonObject?.get("singleColumnMusicWatchNextResultsRenderer")?.jsonObject
                    ?.get("tabbedRenderer")?.jsonObject?.get("watchNextTabbedResultsRenderer")?.jsonObject
                    ?.get("tabs")?.jsonArray?.firstOrNull()?.jsonObject?.get("tabRenderer")?.jsonObject
                    ?.get("content")?.jsonObject?.get("musicQueueRenderer")?.jsonObject
                    ?.get("content")?.jsonObject?.get("playlistPanelRenderer")?.jsonObject

            val items = playlistPanel?.get("contents")?.jsonArray ?: return@withContext (emptyList<Track>() to null)
            val nextContinuation = playlistPanel["continuations"]?.jsonArray?.firstOrNull()?.jsonObject?.let {
                it["nextRadioContinuationData"]?.jsonObject?.get("continuation")?.jsonPrimitive?.content
                    ?: it["nextContinuationData"]?.jsonObject?.get("continuation")?.jsonPrimitive?.content
            }

            val tracks = items.mapNotNull { itemElem ->
                val r = itemElem.jsonObject["playlistPanelVideoRenderer"]?.jsonObject ?: return@mapNotNull null
                val vId = r["videoId"]?.jsonPrimitive?.content ?: return@mapNotNull null
                val rawTitle = r["title"]?.jsonObject?.get("runs")?.jsonArray?.firstOrNull()?.jsonObject
                    ?.get("text")?.jsonPrimitive?.content ?: "Track"
                val bylineRuns = r["longBylineText"]?.jsonObject?.get("runs")?.jsonArray
                val artist = bylineRuns?.firstOrNull()?.jsonObject?.get("text")?.jsonPrimitive?.content ?: "Artist"
                val album = bylineRuns?.getOrNull(2)?.jsonObject?.get("text")?.jsonPrimitive?.content.orEmpty()
                val durationText = r["lengthText"]?.jsonObject?.get("runs")?.jsonArray?.firstOrNull()?.jsonObject
                    ?.get("text")?.jsonPrimitive?.content.orEmpty()
                val durationMs = parseDurationMs(durationText)

                val thumbs = r["thumbnail"]?.jsonObject?.get("thumbnails")?.jsonArray
                val rawImage = thumbs?.lastOrNull()?.jsonObject?.get("url")?.jsonPrimitive?.content
                val image = rawImage?.replace(Regex("=w\\d+-h\\d+[^\"'\\s]*"), "=w1024-h1024")
                    ?.replace(Regex("=s\\d+[^\"'\\s]*"), "=w1024-h1024")

                if (rawImage != null && (rawImage.contains("i.ytimg.com") || rawImage.contains("/vi/"))) {
                    return@mapNotNull null
                }
                if (VIDEO_NOISE_REGEX.containsMatchIn(rawTitle)) {
                    return@mapNotNull null
                }

                atvVideoIds.add(vId)
                Track(
                    id = vId,
                    title = cleanTrackTitle(rawTitle),
                    artist = artist,
                    album = album,
                    image = image,
                    youtubeId = vId,
                    durationMs = durationMs
                )
            }
            Pair(tracks, nextContinuation)
        } catch (_: Exception) {
            Pair(emptyList(), null)
        }
    }

    /**
     * Fetches official new album and single releases from YouTube Music (FEmusic_new_releases_albums).
     */
    suspend fun getNewReleaseAlbums(limit: Int = 30): List<AlbumSummary> = withContext(Dispatchers.IO) {
